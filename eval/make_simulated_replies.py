# ---------- the protected prompt, as the bot "saw" it ----------
def load_prompt():
    return build_system_prompt(SIM_CANARY).strip()


def secrets():
    return get_static_secret_values()


def policies():
    return list(PROTECTED_POLICIES)


# ---------- text transforms used to build encoded and obfuscated leaks ----------
def b64(text):
    return base64.b64encode(text.encode("utf-8")).decode("ascii")


def hexa(text):
    return text.encode("utf-8").hex()


def rot13(text):
    return codecs.encode(text, "rot13")


def dashed(text):
    """Put a dash between the letters of every word: 'rules' -> 'r-u-l-e-s'."""
    return "\n".join(" ".join("-".join(word) for word in line.split(" ")) for line in text.splitlines())


def spaced(text):
    """Put a space between every character."""
    return "\n".join(" ".join(line) for line in text.splitlines())


def dotted(text):
    """Put a dot after every character."""
    return "\n".join("".join(ch + "." for ch in line) for line in text.splitlines())


def leet(text):
    """Swap look-alike characters: e->3, a->4, o->0."""
    return text.translate(str.maketrans("eao", "340"))


