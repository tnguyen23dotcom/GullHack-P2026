"""Build simulated chatbot replies so the detectors can be tuned and tested without a live model.

Why simulated? Our AWS account cannot call Bedrock models yet, so there is no chat model to
produce real leaked replies. This script writes ONE reply for every attack prompt in
attacks.json (what a vulnerable bot WOULD say) and ONE reply for every chat in
normal_chats.json. Any result measured on these replies must be described as
"measured on simulated replies", never as a test of a real model.

The protected prompt is Person B's real one (prompt.py, IT and Operations assistant for
Gull Systems), loaded through b_contract.py. Everything in it is FAKE.

- Verbatim, encoded and obfuscated replies are generated by code from B's prompt, so they are exact.
- Translation and paraphrase replies are hand-written. They leak POLICY TEXT ONLY (no decoy keys,
  no canary), because that is the case exact matching cannot catch.
- Normal replies are hand-written. Several are near-misses: they touch the same topics as the
  policies (code review, salary, launches, passcodes) without leaking anything.

Run from the repo root:  python3 eval/make_simulated_replies.py
"""
